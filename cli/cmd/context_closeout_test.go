// closeoutPlanFixture writes a plan whose ledger holds the facts a closeout is
// supposed to carry: two completed items, a review verdict and a gate line.
func closeoutPlanFixture(t *testing.T, dir string) string {
	t.Helper()
	rel := "context/plan/20260101-000000-closeout-plan.md"
	writeTestFile(t, filepath.Join(dir, rel), `---
kind: plan
uid: `+cascadeUIDFor(rel)+`
summary: a plan whose ledger already holds the closeout
status: active
updated: `+cascadeFixedTime+`
objective: closeout
---

## Objective

Do the thing.

## Phases

## Phase 1 — Work

- [x] first item

## Phase 2 — More

- [x] second item

## Review

- CONFIRMED — phase 1 ran the suite

### Gate

- `+"`sdt agent gate`"+` passed on 2026-01-02
`)
	return rel
}

// TestContextCloseRecordsCloseoutFromTheLedger is the X2 gate: the closeout is
// no longer retyped by hand — the item states, the review verdicts and the gate
// result come out of the plan, and only the fields a command cannot know stay
// marked for the author.
func TestContextCloseRecordsCloseoutFromTheLedger(t *testing.T) {
	dir := setupContextProject(t)
	stubContextNow(t, time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	rel := closeoutPlanFixture(t, dir)

	execute(t, contextCloseCmd, nil, rel)

	if got := frontmatterField(mustReadFile(t, filepath.Join(dir, rel)), ctxMapStatus); got != taskFileStatusCompleted {
		t.Fatalf("plan status = %q, want completed", got)
	}
	entries, err := dirFiles(sdtWorklogDir)
	if err != nil || len(entries) != 1 {
		t.Fatalf("worklog entries = %v (%v), want exactly one", entries, err)
	}
	content := mustReadFile(t, entries[0])
	if got := strings.Join(parseFrontmatterList(content, ctxFrontmatterLinks), ","); !strings.Contains(got, "plan/20260101-000000-closeout-plan.md") {
		t.Errorf("the worklog entry does not link the plan: %q", got)
	}
	for _, want := range []string{
		"### Closeout — 2026-01-02 — closeout-plan",
		"- **Plan ref**: `plan/20260101-000000-closeout-plan.md`",
		"- [x] first item — **expected**",
		"- [x] second item — **expected**",
		"CONFIRMED — phase 1 ran the suite",
		"sdt agent gate` passed on 2026-01-02",
		"- **Files affected**: _",
		"- **Lessons / Do-Not-Repeat candidates**: _",
		"- **Signal review**: _",
		"- **Deviations / blockers**: _",
		"generated by `sdt context close`",
	} {
		if !strings.Contains(content, want) {
			t.Errorf("closeout missing %q:\n%s", want, content)
		}
	}
	if strings.Contains(content, "**open**") {
		t.Errorf("closeout reports open items for a fully ticked plan:\n%s", content)
	}
}

// TestContextCloseCloseoutRerunKeepsTheHumanFields proves the block is one per
// identity: a second close refreshes the derived part and keeps what the author
// wrote.
func TestContextCloseCloseoutRerunKeepsTheHumanFields(t *testing.T) {
	dir := setupContextProject(t)
	stubContextNow(t, time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	rel := closeoutPlanFixture(t, dir)

	execute(t, contextCloseCmd, nil, rel)
	entries, err := dirFiles(sdtWorklogDir)
	if err != nil || len(entries) != 1 {
		t.Fatalf("worklog entries = %v (%v), want one", entries, err)
	}
	entry := entries[0]
	content := strings.Replace(mustReadFile(t, entry),
		"- **Files affected**: _fill with the paths touched by the delivery_",
		"- **Files affected**: cli/cmd/context_closeout.go", 1)
	if err := os.WriteFile(entry, []byte(content), 0o644); err != nil { //#nosec G306 -- test fixture
		t.Fatal(err)
	}

	// The status is terminal now: the second close is the rerun under test.
	execute(t, contextCloseCmd, nil, rel, "--allow-unfinished", "--reason", "rerun")

	content = mustReadFile(t, entry)
	if n := strings.Count(content, "### Closeout — "); n != 1 {
		t.Fatalf("closeout blocks = %d, want one:\n%s", n, content)
	}
	if !strings.Contains(content, "- **Files affected**: cli/cmd/context_closeout.go") {
		t.Errorf("the hand-written field was lost on rerun:\n%s", content)
	}
	if !strings.Contains(content, "- [x] first item — **expected**") {
		t.Errorf("the derived part was not regenerated:\n%s", content)
	}
}

// TestCloseoutPrefersTheRecordedGateRun: a `sdt agent gate --record` run is the
// strongest evidence the section holds, so a prose claim above it does not win.
func TestCloseoutPrefersTheRecordedGateRun(t *testing.T) {
	body := "## Review\n\n- a verdict\n\n### Gate\n\n- a prose claim\n\n" +
		"2026-01-02T00:00:00Z (sdt agent gate) — passed\n- build: pass\n"
	_, verdicts, gate := closeoutScanLedger(body)
	if len(verdicts) != 1 || verdicts[0] != "- a verdict" {
		t.Errorf("verdicts = %v, want the review line only", verdicts)
	}
	if gate != "2026-01-02T00:00:00Z (sdt agent gate) — passed" {
		t.Errorf("gate = %q, want the recorded run", gate)
	}
}

