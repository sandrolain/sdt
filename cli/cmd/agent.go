// agentPrompt asks for a value on the terminal. When yes is set, or stdin is
// not a terminal, the default is returned without prompting.

func agentPrompt(cmd *cobra.Command, yes bool, label, def string) string {
	if yes || !stdinIsTTY() {
		return def
	}
	if _, ferr := fmt.Fprintf(cmd.ErrOrStderr(), "%s [%s]: ", label, def); ferr != nil {
		_ = ferr
	}
	line, err := bufio.NewReader(cmd.InOrStdin()).ReadString('\n')
	if err != nil && err != io.EOF {
		return def
	}
	line = strings.TrimSpace(line)
	if line == "" {
		return def
	}
	return line
}

// resolveGitIgnoreMode decides which context entries go into .gitignore.
// A --gitignore flag value wins. When omitted the mode is asked interactively
// (confirm first, then which entries); non-interactive runs and --yes default
// to work, preserving the historical behavior.

func agentPromptBool(cmd *cobra.Command, yes bool, label string, def bool) bool {
	if yes || !stdinIsTTY() {
		return def
	}
	d := "n"
	if def {
		d = "y"
	}
	if _, ferr := fmt.Fprintf(cmd.ErrOrStderr(), "%s [%s]: ", label, d); ferr != nil {
		_ = ferr
	}
	line, err := bufio.NewReader(cmd.InOrStdin()).ReadString('\n')
	if err != nil && err != io.EOF {
		return def
	}
	switch strings.ToLower(strings.TrimSpace(line)) {
	case "y", "yes", "1":
		return true
	case "n", "no", "0":
		return false
	}
	if b, perr := strconv.ParseBool(strings.TrimSpace(line)); perr == nil {
		return b
	}
	return def
}

// agentPromptGitIgnoreMode asks which context entries to ignore. Accepted
// input is a comma-separated list of numbers or keywords: 1/tmp, 2/docs,
// 3/context (entire directory), or work for both tmp and docs. Empty input and
// unrecognized tokens fall back to def.

func stdinIsTTY() bool {
	fi, err := os.Stdin.Stat()
	if err != nil {
		return false
	}
	return fi.Mode()&os.ModeCharDevice != 0
}

func defaultProjectName() string {
	cwd, err := os.Getwd()
	if err != nil {
		return ""
	}
	sum := sha256.Sum256([]byte(cwd))
	return fmt.Sprintf("%s_%x", filepath.Base(cwd), sum[:4])
}

// loadProjectConfig reads a project config file, returning nil on any error.

func loadProjectConfig(path string) *ProjectConfig {
	data, err := os.ReadFile(path) //#nosec G304 -- user-chosen config path
	if err != nil {
		return nil
	}
	var cfg ProjectConfig
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return nil
	}
	return &cfg
}

// fill copies non-empty fields from existing into cfg, preserving prior values.
func (cfg *ProjectConfig) fill(existing *ProjectConfig) {
	if existing == nil {
		return
	}
	if existing.Project != "" {
		cfg.Project = existing.Project
	}
	if existing.Group != "" {
		cfg.Group = existing.Group
	}
}

// ensureWorkDirs creates the context/ working directory layout.

func ensureWorkDirs(force bool) []FileResult {
	dirs := []string{sdtWorkDir, sdtPlanDir, sdtAnalysisDir, sdtWorklogDir, sdtNotesDir, sdtTasksDir, sdtDeprecatedDir, sdtTmpDir, sdtInstrDir, sdtCommandsDir, sdtArchitectureDir, sdtDecisionsDir, sdtQuestionsDir, sdtProposalsDir, sdtPromptsDir, sdtResearchDir, sdtScriptsDir, sdtRolesDir}
	var results []FileResult
	for _, d := range dirs {
		res := FileResult{Path: d + "/"}
		fi, err := os.Stat(d)
		if err == nil {
			if fi.IsDir() {
				res.Status = statusSkipped
				res.Reason = "directory already exists"
			} else {
				res.Status = statusError
				res.Reason = "exists and is not a directory"
			}
		} else if os.IsNotExist(err) {
			if err := os.MkdirAll(d, 0o750); err != nil { //#nosec G301
				res.Status = statusError
				res.Reason = err.Error()
			} else {
				res.Status = statusCreated
			}
		} else {
			res.Status = statusError
			res.Reason = err.Error()
		}
		results = append(results, res)
	}

	files := []struct {
		path    string
		content string
	}{
		{sdtWorkReadme, sdtWorkReadmeContent()},
		{sdtScriptsIndex, scriptsIndexTemplate},
		{ctxTopicsFilePath, topicsRegisterTemplate},
		{ctxCategoriesFilePath, categoriesRegisterTemplate},
		{ctxMemoFilePath, memoRegisterTemplate},
		{ctxTodoFilePath, todoRegisterTemplate},
	}
	for _, f := range files {
		res := FileResult{Path: f.path}
		if _, err := os.Stat(f.path); os.IsNotExist(err) {
			if err := os.WriteFile(f.path, []byte(f.content), 0o644); err != nil { //#nosec G306 -- user-chosen output
				res.Status = statusError
				res.Reason = err.Error()
			} else {
				res.Status = statusCreated
			}
		} else if err == nil {
			res.Status = statusSkipped
			res.Reason = "file already exists"
		} else {
			res.Status = statusError
			res.Reason = err.Error()
		}
		results = append(results, res)
	}
	return results
}

