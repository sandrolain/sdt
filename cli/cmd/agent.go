// writeInstructionFiles creates the instruction files under context/instructions/.
// It is non-destructive: existing files are preserved unless force is set.
func writeInstructionFiles(project, group string, force bool) []FileResult {
	var results []FileResult
	for _, f := range instructionFiles(project, group) {
		path := filepath.Join(sdtInstrDir, f.name)
		res := FileResult{Path: path}
		existed := false
		if _, err := os.Stat(path); err == nil {
			existed = true
			if !force {
				res.Status = statusSkipped
				res.Reason = "file already exists (use --force to overwrite)"
				results = append(results, res)
				continue
			}
		} else if !os.IsNotExist(err) {
			res.Status = statusError
			res.Reason = err.Error()
			results = append(results, res)
			continue
		}
		if err := os.MkdirAll(sdtInstrDir, 0o750); err != nil { //#nosec G301
			res.Status = statusError
			res.Reason = err.Error()
			results = append(results, res)
			continue
		}
		if err := os.WriteFile(path, []byte(f.body), 0o644); err != nil { //#nosec G306 -- user-chosen output
			res.Status = statusError
			res.Reason = err.Error()
			results = append(results, res)
			continue
		}
		if existed {
			res.Status = statusUpdated
		} else {
			res.Status = statusCreated
		}
		results = append(results, res)
	}
	if force {
		for _, name := range obsoleteInstructionFiles {
			path := filepath.Join(sdtInstrDir, name)
			if _, err := os.Stat(path); os.IsNotExist(err) {
				continue
			} else if err != nil {
				results = append(results, FileResult{Path: path, Status: statusError, Reason: err.Error()})
				continue
			}
			if err := os.Remove(path); err != nil {
				results = append(results, FileResult{Path: path, Status: statusError, Reason: err.Error()})
				continue
			}
			results = append(results, FileResult{Path: path, Status: statusRemoved, Reason: "obsolete (no longer generated)"})
		}
	}
	return results
}

