// briefingScaffoldTemplate is the starter briefing `agent init` writes so a
// project has an onboarding surface to fill. It carries the contract and empty
// sections, never facts.
const briefingScaffoldTemplate = `---
kind: briefing
subject: onboarding
status: draft
summary: "MANDATORY-fill: orient a newcomer on this project"
---

> Derive, don't trust: pair every volatile fact below with the command that
> derives it, so a reader re-derives it instead of trusting a copy. End with a
> dated, second-verified delta.

## Artifacts

## Map

## Roles

## Rules

## Derived facts

## Delta

2026-10-11 — <replace this dated example with the first second-verified change>
`

// briefingScaffoldContent gives each generated onboarding document its own
// immutable UID. Without it, making briefing reachable from corpus lint would
// make every fresh agent init report its own scaffold as incomplete.
func briefingScaffoldContent() string {
	return strings.Replace(briefingScaffoldTemplate,
		"kind: briefing\n",
		"kind: briefing\nuid: "+newUID()+"\n",
		1,
	)
}

// sdtWorkReadmeContent renders the generated context/README.md: the static
// layout/conventions prose from workspace/readme.md.tmpl (shell of the file)
// plus the registry-driven Commands block.

func sdtWorkReadmeContent() string {
	return templates.Must("workspace/readme.md.tmpl", struct{ CommandsSection string }{CommandsSection: sdtWorkCommandsSection()}, nil)
}

