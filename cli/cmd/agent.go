// gitIgnoreTmpEntry keeps sdt.context/tmp out of version control. The pattern is
// not root-anchored so it also applies when sdt.context lives in a subdirectory.
const gitIgnoreTmpEntry = "sdt.context/tmp/"

// gitIgnoreDocsEntry keeps generated agent docs out of version control. The
// reference is regenerated per binary version, so it is never committed.
const gitIgnoreDocsEntry = "sdt.context/docs/"

// gitIgnoreEntries lists the sdt.context/ entries ensured by ensureGitIgnore.
var gitIgnoreEntries = []string{gitIgnoreTmpEntry, gitIgnoreDocsEntry}

// findGitRepoRoot walks up from the current directory looking for a .git entry
// (directory or worktree file). It returns the repository root, or "" when the
// current directory is not inside a git repository.
func findGitRepoRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		return ""
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, ".git")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

// ensureGitIgnore ensures the repository .gitignore ignores the sdt.context
// working directories that are generated or transient (tmp, docs). It creates
// the file when missing, appends each entry only when absent, and returns nil
// when no git repository is detected.
func ensureGitIgnore() *FileResult {
	root := findGitRepoRoot()
	if root == "" {
		return nil
	}
	path := filepath.Join(root, ".gitignore")
	res := &FileResult{Path: path}
	existing := ""
	if data, err := os.ReadFile(path); err == nil { //#nosec G304 -- repo root derived from cwd walk-up
		existing = string(data)
	} else if !os.IsNotExist(err) {
		res.Status = statusError
		res.Reason = err.Error()
		return res
	}
	content := existing
	added := false
	for _, entry := range gitIgnoreEntries {
		if gitIgnoreHasEntry(content, entry) {
			continue
		}
		if content != "" && !strings.HasSuffix(content, "\n") {
			content += "\n"
		}
		content += entry + "\n"
		added = true
	}
	if !added {
		res.Status = statusSkipped
		res.Reason = "entries already present"
		return res
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil { //#nosec G306,G703 -- repo root derived from cwd walk-up
		res.Status = statusError
		res.Reason = err.Error()
		return res
	}
	if existing == "" {
		res.Status = statusCreated
	} else {
		res.Status = statusUpdated
	}
	return res
}

// gitIgnoreHasEntry reports whether content already contains entry as a line,
// tolerating a missing trailing slash and surrounding whitespace.
func gitIgnoreHasEntry(content, entry string) bool {
	base := strings.TrimSuffix(entry, "/")
	for _, line := range strings.Split(content, "\n") {
		line = strings.TrimSpace(line)
		if line == entry || line == base {
			return true
		}
	}
	return false
}

// agentMergeTarget ensures AGENTS.md carries the single instructions block
// without destroying custom content. With force the block is refreshed.
func agentMergeTarget(target, project, group string, force bool) (FileResult, string) {
	res := FileResult{Path: target}
	content := ""
	if _, err := os.Stat(target); err == nil {
		data, rerr := os.ReadFile(target) //#nosec G304 -- user-chosen target file
		if rerr != nil {
			res.Status = statusError
			res.Reason = rerr.Error()
			return res, content
		}
		content = string(data)
	}

	newContent, changed := agentMergeBlock(content, agentSectionNameInstructions, agentBlockInstructions(project, group), force)
	if !changed {
		res.Status = statusSkipped
		res.Reason = "AGENTS.md already up to date"
	} else if strings.TrimSpace(content) == "" {
		res.Status = statusCreated
	} else {
		res.Status = statusUpdated
	}
	return res, newContent
}

