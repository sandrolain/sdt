// TestAgentBlockMatchesInstructionFiles (B7) ensures every instruction file
// referenced by the block is exactly the set generated by instructionFiles.
func TestAgentBlockMatchesInstructionFiles(t *testing.T) {
	block := agentBlockInstructions("p", "g")
	files := instructionFiles("p", "g")
	for _, f := range files {
		want := "sdt.context/instructions/" + f.name
		if !strings.Contains(block, "`"+want+"`") {
			t.Errorf("block does not reference generated file %s", want)
		}
	}
	for _, line := range strings.Split(block, "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "- `sdt.context/instructions/") {
			continue
		}
		start := strings.Index(line, "`")
		if start < 0 {
			continue
		}
		rest := line[start+1:]
		end := strings.Index(rest, "`")
		if end < 0 {
			continue
		}
		ref := rest[:end]
		found := false
		for _, f := range files {
			if ref == "sdt.context/instructions/"+f.name {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("block references %s which is not generated", ref)
		}
	}
}
