func TestContextDocs(t *testing.T) {
	dir := runInTempDir(t)
	stubContextNow(t, time.Date(2026, 8, 6, 7, 0, 0, 0, time.UTC))

	var leaves []docsCommand
	for _, sub := range rootCmd.Commands() {
		collectLeafCommands(sub, "", &leaves)
	}

	out := execute(t, contextDocsCmd, nil)
	if !strings.Contains(string(out), "README.md") {
		t.Errorf("expected README in output: %s", out)
	}
	docsDir := filepath.Join(dir, "sdt.context", "docs")
	for _, f := range []string{"README.md", "context-task-add.md", "memory-set.md"} {
		if _, err := os.Stat(filepath.Join(docsDir, f)); err != nil {
			t.Errorf("expected %s generated: %v", f, err)
		}
	}
	entries, err := os.ReadDir(docsDir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != len(leaves)+1 {
		t.Errorf("expected %d files, got %d", len(leaves)+1, len(entries))
	}

	readme, _ := os.ReadFile(filepath.Join(docsDir, "README.md"))
	if !strings.Contains(string(readme), "Generated by `sdt` dev at 2026-08-06T07:00:00Z") {
		t.Errorf("expected deterministic timestamp in README:\n%s", readme)
	}
}

func TestContextDocsIdempotent(t *testing.T) {
	dir := runInTempDir(t)
	stubContextNow(t, time.Date(2026, 8, 6, 7, 0, 0, 0, time.UTC))

	execute(t, contextDocsCmd, nil)
	out := execute(t, contextDocsCmd, nil)
	if strings.Contains(string(out), "[created]") {
		t.Errorf("expected no created status on second run: %s", out)
	}
	if !strings.Contains(string(out), "[updated]") {
		t.Errorf("expected updated status on second run: %s", out)
	}
	docsDir := filepath.Join(dir, "sdt.context", "docs")
	entries, err := os.ReadDir(docsDir)
	if err != nil {
		t.Fatal(err)
	}
	var leaves []docsCommand
	for _, sub := range rootCmd.Commands() {
		collectLeafCommands(sub, "", &leaves)
	}
	if len(entries) != len(leaves)+1 {
		t.Errorf("expected stable file count %d, got %d", len(leaves)+1, len(entries))
	}
}

func TestContextDocsClean(t *testing.T) {
	dir := runInTempDir(t)
	execute(t, contextDocsCmd, nil)
	stale := filepath.Join(dir, "sdt.context", "docs", "zz-stale.md")
	if err := os.WriteFile(stale, []byte("old"), 0o644); err != nil {
		t.Fatal(err)
	}
	out := execute(t, contextDocsCmd, nil, "--clean")
	if !strings.Contains(string(out), "zz-stale.md") || !strings.Contains(string(out), "stale") {
		t.Errorf("expected stale removal in output: %s", out)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Error("expected stale file removed")
	}
}

