func TestDocFileName(t *testing.T) {
	for in, want := range map[string]string{
		"context task add": "context-task-add.md",
		"jwt parse":        "jwt-parse.md",
		"memory set":       "memory-set.md",
	} {
		if got := docFileName(in); got != want {
			t.Errorf("docFileName(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestCollectLeafCommands(t *testing.T) {
	var leaves []docsCommand
	for _, sub := range rootCmd.Commands() {
		collectLeafCommands(sub, "", &leaves)
	}
	if len(leaves) == 0 {
		t.Fatal("expected leaf commands")
	}
	names := map[string]bool{}
	for _, d := range leaves {
		if d.file == "" || d.path == "" {
			t.Errorf("empty path/file for %+v", d)
		}
		if names[d.file] {
			t.Errorf("duplicate file %q", d.file)
		}
		names[d.file] = true
		if d.c.Name() == "help" || d.c.Name() == "completion" {
			t.Errorf("unexpected default command in docs: %s", d.path)
		}
	}
	if !names["context-task-add.md"] {
		t.Error("expected context-task-add.md among leaves")
	}
}

func TestRenderCommandDoc(t *testing.T) {
	var leaves []docsCommand
	for _, sub := range rootCmd.Commands() {
		collectLeafCommands(sub, "", &leaves)
	}
	var target *docsCommand
	for i := range leaves {
		if leaves[i].path == "context task add" {
			target = &leaves[i]
			break
		}
	}
	if target == nil {
		t.Fatal("expected context task add command")
	}
	doc := renderCommandDoc(*target)
	for _, want := range []string{
		"# sdt context task add",
		"Generated by `sdt`",
		"## Usage",
		"## Description",
		"## Flags",
		"`objective`",
		"## Global Flags",
		"`format`",
		"## Input / Output",
		"stdin | `--input` | `--file` | `--inb64`",
	} {
		if !strings.Contains(doc, want) {
			t.Errorf("expected %q in command doc:\n%s", want, doc)
		}
	}
}

